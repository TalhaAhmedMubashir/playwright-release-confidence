// Honest signal: the numbers in the README are generated from the suite itself, never typed. CI runs
// this with --check and fails when the README no longer matches the tests.
// Usage: node scripts/readme-numbers.ts [--check]
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import type { JSONReport } from '@playwright/test/reporter';
import { type Outcome, outcomes } from './report.ts';

export const START = '<!-- numbers:start (generated by scripts/readme-numbers.ts; do not edit) -->';
export const END = '<!-- numbers:end -->';

/** The README's table: tests per area, how many are known bugs, and where they run. */
export function numbers(list: Outcome[]): string {
  const areas = [...new Set(list.map((outcome) => outcome.area))].filter((area) => area !== 'Setup');
  const unique = (outcomesOf: Outcome[]) => new Set(outcomesOf.map((outcome) => `${outcome.file} ${outcome.title}`)).size;
  const rows = areas.map((area) => {
    const mine = list.filter((outcome) => outcome.area === area);
    const projects = [...new Set(mine.map((outcome) => outcome.project))].join(', ');
    return `| ${area} | ${unique(mine)} | ${unique(mine.filter((outcome) => outcome.knownBug))} | ${projects} |`;
  });
  const tests = list.filter((outcome) => outcome.area !== 'Setup');
  return [
    START,
    '| Area | Tests | Known bugs (expected to fail) | Runs in |',
    '|---|---|---|---|',
    ...rows,
    `| **All** | **${unique(tests)}** | **${unique(tests.filter((outcome) => outcome.knownBug))}** | ${tests.length} runs across projects |`,
    END,
  ].join('\n');
}

/** The README with its numbers block replaced; throws if the markers are missing. */
export function withNumbers(readme: string, block: string): string {
  const start = readme.indexOf(START);
  const end = readme.indexOf(END);
  if (start < 0 || end < start) throw new Error('README.md has no numbers block (its start and end markers).');
  return readme.slice(0, start) + block + readme.slice(end + END.length);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const list = execFileSync(process.execPath, ['node_modules/@playwright/test/cli.js', 'test', '--list', '--reporter=json'], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  const readme = readFileSync('README.md', 'utf8');
  const updated = withNumbers(readme, numbers(outcomes(JSON.parse(list) as JSONReport)));
  if (process.argv.includes('--check')) {
    if (updated !== readme) {
      console.error('The numbers in README.md no longer match the tests. Run: npm run readme:numbers');
      process.exitCode = 1;
    } else {
      console.log('The numbers in README.md match the tests.');
    }
  } else {
    writeFileSync('README.md', updated);
    console.log('README.md numbers updated.');
  }
}
